create table public.paper_bot_ledgers (
  bot_id text primary key check (bot_id ~ '^[a-z0-9][a-z0-9-]{1,63}$'),
  display_name text not null check (char_length(display_name) between 1 and 120),
  status text not null check (status in ('active','planned','paused')),
  strategy_id text,
  strategy_version integer check (strategy_version is null or strategy_version > 0),
  starting_cash numeric(18,6) not null check (starting_cash > 0),
  cash numeric(18,6) not null,
  equity numeric(18,6) not null check (equity >= 0),
  realized_pl numeric(18,6) not null default 0,
  unrealized_pl numeric(18,6) not null default 0,
  buying_power numeric(18,6),
  peak_equity numeric(18,6) not null check (peak_equity >= 0),
  current_drawdown_pct numeric(10,6) not null default 0 check (current_drawdown_pct <= 0),
  open_planned_risk_pct numeric(10,6),
  correlated_risk_pct numeric(10,6),
  daily_realized_loss_pct numeric(10,6),
  weekly_drawdown_pct numeric(10,6),
  last_synced_at timestamptz,
  source text not null default 'virtual',
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

